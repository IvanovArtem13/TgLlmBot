namespace TgLlmBot.Services.Media;

/// <summary>
///     Потолок длины описаний вложений.
/// </summary>
/// <remarks>
///     В историю чата вложение попадает текстовым описанием - само оно в контекст не возвращается.
///     Описание готовится сразу компактным: модель видит вложение и историю чата одним запросом
///     и укладывает всё важное в потолок, длиннее которого в истории делать нечего.
/// </remarks>
public static class MediaDescriptionLimits
{
    /// <summary>
    ///     Потолок описания - того, что уезжает в историю с каждым сообщением.
    /// </summary>
    public const int ShortMaxLength = 1000;
}
