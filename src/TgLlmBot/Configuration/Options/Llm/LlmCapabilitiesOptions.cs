namespace TgLlmBot.Configuration.Options.Llm;

/// <summary>
///     Капабилити основной модели: какие виды вложений она способна увидеть сама.
/// </summary>
/// <remarks>
///     Отдельной модели для распознавания вложений нет: если модель умеет в картинку или видео,
///     вложение уезжает в запрос к ней само по себе. Чего модель не видит - то не обрабатывается
///     вовсе, ни основной файл, ни статическое превью: показывать модели один кадр видео незачем,
///     если видео она смотреть не умеет, - вместо этого модель прямо говорит, что распознавание
///     такого вложения не поддерживается.
/// </remarks>
public class LlmCapabilitiesOptions
{
    /// <summary>
    ///     Модель видит картинки: фото, статические стикеры, превью движущихся вложений.
    /// </summary>
    public bool Image { get; set; }

    /// <summary>
    ///     Модель видит видео: видео и гифки целиком, анимированные и видео-стикеры.
    /// </summary>
    public bool Video { get; set; }

    /// <summary>
    ///     Модель слышит аудио. Зарезервировано на будущее: голосовых сообщений бот пока
    ///     не обрабатывает в принципе.
    /// </summary>
    public bool Audio { get; set; }
}
